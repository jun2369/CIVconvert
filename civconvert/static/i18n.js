  const DICTS = { en: EN, zh: ZH };
  let lang = store.get(LANG_KEY) === "zh" ? "zh" : "en";

  const has = (key) => key in DICTS[lang] || key in EN;
  function t(key, params) {
    const text = DICTS[lang][key] ?? EN[key];
    if (text === undefined) return key;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined || params[k] === null ? "" : String(params[k])));
  }

  /** Static texts in the HTML: data-i18n (text), data-i18n-placeholder / -title / -aria. */
  function apply(root = document) {
    for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
    for (const node of root.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
    for (const node of root.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
    for (const node of root.querySelectorAll("[data-i18n-aria]")) node.setAttribute("aria-label", t(node.dataset.i18nAria));
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }

  /** An error answer of the API in the current language. */
  function error(data, fallback = "") {
    if (data && data.code && has("err." + data.code)) return t("err." + data.code, data.params || {});
    return (data && (data.error || (typeof data.detail === "string" ? data.detail : ""))) || fallback;
  }

  /** A problem flag {code, params, message} in the current language. */
  function flag(f) {
    if (!f) return "";
    const key = "flag." + f.code;
    if (!f.code || !has(key)) return f.message || "";
    const p = { ...(f.params || {}) };
    if (Array.isArray(p.others)) p.others = p.others.map((o) => t(key + ".item", o)).join(t("list.sep"));
    if (Array.isArray(p.names)) p.names = p.names.join(", ");
    if (p.inner) p.inner = flag(p.inner);
    return t(key, p);
  }

  /** Names of the PDF checks ("Subtotal qty", "Line math" …). */
  function checkName(name) {
    if (has("check." + name)) return t("check." + name);
    const m = /^Subtotal (.+)$/.exec(name);
    return m ? t("check.Subtotal_field", { field: m[1] }) : name;
  }

  /** The detail of a PDF check {name, ok, detail, code, params}. */
  function checkDetail(c) {
    if (!c) return "";
    const key = "checkd." + c.code;
    if (!c.code || !has(key)) return c.detail || "";
    const p = { ...(c.params || {}) };
    if (Array.isArray(p.lines)) p.lines = p.lines.join(t("list.sep"));
    return t(key, p);
  }

